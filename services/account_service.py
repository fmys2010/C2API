    @staticmethod
    def _now() -> str:
        return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")

    @staticmethod
    def _decode_jwt_payload(token: str) -> dict:
        try:
            payload = str(token or "").split(".")[1]
            payload += "=" * ((4 - len(payload) % 4) % 4)
            import base64
            import json
            data = json.loads(base64.urlsafe_b64decode(payload.encode("ascii")))
            return data if isinstance(data, dict) else {}
        except Exception:
            return {}

    @staticmethod
    def _parse_time(value: object) -> datetime | None:
        raw = str(value or "").strip()
        if not raw:
            return None
        try:
            parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        except Exception:
            try:
                parsed = datetime.strptime(raw, "%Y-%m-%d %H:%M:%S")
            except Exception:
                return None
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        return parsed.astimezone(timezone.utc)

    @staticmethod
    def _timestamp_to_iso(value: object) -> str:
        try:
            ts = int(value)
        except (TypeError, ValueError):
            return ""
        tz = timezone(timedelta(hours=8))
        return datetime.fromtimestamp(ts, tz=timezone.utc).astimezone(tz).isoformat()

    def _load_accounts(self) -> dict[str, dict]:
        accounts = self.storage.load_accounts()
        return {
            normalized["access_token"]: normalized
            for item in accounts
            if (normalized := self._normalize_account(item)) is not None
        }

    def _save_accounts(self) -> None:
        self.storage.save_accounts(list(self._accounts.values()))

    @staticmethod
    def _is_image_account_available(account: dict) -> bool:
        if not isinstance(account, dict):
            return False
        if account.get("status") in {"禁用", "限流", "异常"}:
            return False
        return int(account.get("quota") or 0) > 0

    @classmethod
    def _account_matches_plan_type(cls, account: dict, plan_type: str | None = None) -> bool:
        if not plan_type:
            return True
        normalized_plan = cls._normalize_account_type(plan_type)
        normalized_account = cls._normalize_account_type(account.get("type"))
        if not normalized_plan or not normalized_account:
            return False
        return normalized_plan.lower() == normalized_account.lower()

    @classmethod
    def _account_matches_source_type(cls, account: dict, source_type: str | None = None) -> bool:
        if not source_type:
            return True
        return cls._normalize_source_type(account.get("source_type")) == cls._normalize_source_type(source_type)

    @classmethod
    def _account_matches_any_plan_type(cls, account: dict, plan_types: set[str] | tuple[str, ...] | None = None) -> bool:
        if not plan_types:
            return True
        normalized_account = cls._normalize_account_type(account.get("type"))
        normalized_plans = {
            normalized
            for plan_type in plan_types
            if (normalized := cls._normalize_account_type(plan_type))
        }
        return bool(normalized_account and normalized_account in normalized_plans)

    @staticmethod
    def _normalize_source_type(value: object) -> str:
        return str(value or "web").strip().lower() or "web"

    @staticmethod
    def _normalize_account_type(value: object) -> str | None:
        raw = str(value or "").strip()
        if not raw:
            return None
        key = raw.lower().replace("-", "_").replace(" ", "_")
        compact = key.replace("_", "")
        aliases = {
            "free": "free",
            "plus": "Plus",
            "pro": "Pro",
            "prolite": "ProLite",
            "team": "Team",
            "business": "Team",
            "enterprise": "Enterprise",
        }
        return aliases.get(compact) or aliases.get(key) or raw

    def _search_account_type(self, payload: object) -> str | None:
        if isinstance(payload, dict):
            for key in ("plan_type", "account_plan", "account_type", "subscription_type", "type"):
                plan = self._normalize_account_type(payload.get(key))
                if plan:
                    return plan
            for value in payload.values():
                plan = self._search_account_type(value)
                if plan:
                    return plan
        elif isinstance(payload, list):
            for value in payload:
                plan = self._search_account_type(value)
                if plan:
                    return plan
        return None

    def _normalize_account(self, item: dict) -> dict | None:
        if not isinstance(item, dict):
            return None
        access_token = item.get("access_token") or item.get("accessToken") or ""
        if not access_token:
            return None
        normalized = dict(item)
        normalized.pop("accessToken", None)
        normalized["access_token"] = access_token
        if str(normalized.get("type") or "").strip().lower() == "codex":
            normalized["export_type"] = "codex"
            normalized.pop("type", None)
        normalized["type"] = normalized.get("type") or "free"
        normalized["status"] = normalized.get("status") or "正常"
        normalized["quota"] = max(0, int(normalized.get("quota") if normalized.get("quota") is not None else 0))
        normalized["email"] = normalized.get("email") or None
        normalized["user_id"] = normalized.get("user_id") or None
        normalized["proxy"] = str(normalized.get("proxy") or "").strip()
        source_type = normalized.get("source_type")
        if not source_type and str(normalized.get("export_type") or "").strip().lower() == "codex":
            source_type = "codex"
        normalized["source_type"] = self._normalize_source_type(source_type)
        limits_progress = normalized.get("limits_progress")
        normalized["limits_progress"] = limits_progress if isinstance(limits_progress, list) else []
        normalized["default_model_slug"] = normalized.get("default_model_slug") or None
        normalized["restore_at"] = normalized.get("restore_at") or None
        normalized["success"] = int(normalized.get("success") or 0)
        normalized["fail"] = int(normalized.get("fail") or 0)
        normalized["invalid_count"] = int(normalized.get("invalid_count") or 0)
        normalized["session_token"] = normalized.get("session_token") or None
        normalized["password"] = normalized.get("password") or None
        normalized["device_id"] = normalized.get("device_id") or None
        normalized["last_used_at"] = normalized.get("last_used_at")
        normalized["last_invalid_at"] = normalized.get("last_invalid_at") or None
        normalized["last_refresh_error"] = normalized.get("last_refresh_error") or None
        normalized["last_refresh_error_at"] = normalized.get("last_refresh_error_at") or None
        normalized["last_token_refresh_at"] = normalized.get("last_token_refresh_at") or None
        normalized["last_token_refresh_error"] = normalized.get("last_token_refresh_error") or None
        normalized["last_token_refresh_error_at"] = normalized.get("last_token_refresh_error_at") or None
        normalized["created_at"] = normalized.get("created_at") or AccountService._now()
        return normalized

    @staticmethod
    def _jwt_exp(access_token: str) -> int:
        try:
            return int(AccountService._decode_jwt_payload(access_token).get("exp") or 0)
        except (TypeError, ValueError):
            return 0

    @classmethod
    def _token_expires_in(cls, access_token: str) -> int | None:
        exp = cls._jwt_exp(access_token)
        if exp <= 0:
            return None
        return exp - int(time.time())

    @classmethod
    def _token_needs_refresh(cls, access_token: str, *, force: bool = False) -> bool:
        if force:
            return True
        remaining = cls._token_expires_in(access_token)
        return remaining is not None and remaining <= cls._ACCESS_TOKEN_REFRESH_SKEW_SECONDS

    @classmethod
    def _token_issued_at(cls, access_token: str) -> datetime | None:
        try:
            iat = int(cls._decode_jwt_payload(access_token).get("iat") or 0)
        except (TypeError, ValueError):
            return None
        if iat <= 0:
            return None
        return datetime.fromtimestamp(iat, tz=timezone.utc)

    @staticmethod
    def _safe_response_text(response: object, limit: int = 300) -> str:
        try:
            return str(getattr(response, "text", "") or "")[:limit]
        except Exception:
            return ""

    def _resolve_access_token_locked(self, access_token: str) -> str:
        token = str(access_token or "").strip()
        seen: set[str] = set()
        while token and token not in self._accounts and token in self._token_aliases and token not in seen:
            seen.add(token)
            token = self._token_aliases.get(token, token)
        return token

    def resolve_access_token(self, access_token: str) -> str:
        if not access_token:
            return ""
        with self._lock:
            return self._resolve_access_token_locked(access_token)

    def _get_account_for_token(self, access_token: str) -> tuple[str, dict | None]:
        with self._lock:
            resolved = self._resolve_access_token_locked(access_token)
            account = self._accounts.get(resolved)
            return resolved, dict(account) if account else None

    def _record_token_refresh_error(self, access_token: str, event: str, error: str) -> None:
        now = datetime.now(timezone.utc).isoformat()
        with self._lock:
            resolved = self._resolve_access_token_locked(access_token)
            current = self._accounts.get(resolved)
            if current is None:
                return
            next_item = dict(current)
            next_item["last_token_refresh_error"] = str(error or "refresh token failed")
            next_item["last_token_refresh_error_at"] = now
            account = self._normalize_account(next_item)
            if account is not None:
                self._accounts[resolved] = account
                self._save_accounts()
        log_service.add(
            LOG_TYPE_ACCOUNT,
            "refresh_token 刷新 access_token 失败",
            {"source": event, "token": anonymize_token(access_token), "error": str(error or "")},
        )

    def _recent_token_refresh_error(self, account: dict) -> bool:
        last_error_at = self._parse_time(account.get("last_token_refresh_error_at"))
        if last_error_at is None:
            return False
        return (datetime.now(timezone.utc) - last_error_at).total_seconds() < self._TOKEN_REFRESH_ERROR_BACKOFF_SECONDS

    def _recent_refresh_token_keepalive_error(self, account: dict, now: datetime) -> bool:
        last_error_at = self._parse_time(account.get("last_token_refresh_error_at"))
        if last_error_at is None:
            return False
        return (now - last_error_at).total_seconds() < self._REFRESH_TOKEN_KEEPALIVE_ERROR_BACKOFF_SECONDS

    def _refresh_token_keepalive_anchor(self, account: dict) -> datetime | None:
        return (
            self._parse_time(account.get("last_token_refresh_at"))
            or self._token_issued_at(str(account.get("access_token") or ""))
            or self._parse_time(account.get("created_at"))
        )

    def _refresh_token_keepalive_due_at(self, account: dict, now: datetime) -> datetime | None:
        if not str(account.get("refresh_token") or "").strip():
            return None
        if account.get("status") == "禁用":
            return None
        if self._recent_refresh_token_keepalive_error(account, now):
            return None
        anchor = self._refresh_token_keepalive_anchor(account)
        if anchor is None:
            return now
        due_at = anchor + timedelta(seconds=self._REFRESH_TOKEN_KEEPALIVE_SECONDS)
        return due_at if due_at <= now else None

    def _request_access_token_refresh(self, refresh_token: str, account: dict | None = None) -> dict[str, str]:
        from curl_cffi import requests
        from services.proxy_service import proxy_settings

        session = requests.Session(**proxy_settings.build_session_kwargs(account=account, impersonate="chrome110", verify=True))
        try:
            response = session.post(
                self._OAUTH_TOKEN_URL,
                headers={
                    "Accept": "application/json",
                    "Content-Type": "application/x-www-form-urlencoded",
                    "User-Agent": self._OAUTH_USER_AGENT,
                },
                data={
                    "grant_type": "refresh_token",
                    "refresh_token": refresh_token,
                    "client_id": self._OAUTH_CLIENT_ID,
                },
                timeout=60,
            )
            data = response.json() if response.text else {}
            if response.status_code != 200 or not isinstance(data, dict) or not data.get("access_token"):
                detail = ""
                if isinstance(data, dict):
                    detail = str(data.get("error_description") or data.get("error") or data.get("message") or "")
                detail = detail or self._safe_response_text(response)
                raise RuntimeError(f"oauth_refresh_http_{response.status_code}{': ' + detail if detail else ''}")
            return {
                "access_token": str(data.get("access_token") or "").strip(),
                "refresh_token": str(data.get("refresh_token") or refresh_token).strip(),
                "id_token": str(data.get("id_token") or "").strip(),
            }
        finally:
            session.close()

    def _apply_refreshed_tokens(self, old_access_token: str, token_data: dict, event: str) -> str:
        now = datetime.now(timezone.utc).isoformat()
        with self._image_slot_condition:
            old_token = self._resolve_access_token_locked(old_access_token)
            current = self._accounts.get(old_token)
            if current is None:
                return old_token
            new_token = str(token_data.get("access_token") or old_token).strip()
            if not new_token:
                return old_token

            next_item = dict(current)
            next_item["access_token"] = new_token
            if token_data.get("refresh_token"):
                next_item["refresh_token"] = str(token_data.get("refresh_token") or "").strip()
            if token_data.get("id_token"):
                next_item["id_token"] = str(token_data.get("id_token") or "").strip()
            if token_data.get("session_token"):
                next_item["session_token"] = str(token_data.get("session_token") or "").strip()
            next_item["last_token_refresh_at"] = now
            next_item["last_token_refresh_error"] = None
            next_item["last_token_refresh_error_at"] = None
            next_item["invalid_count"] = 0
            next_item["last_invalid_at"] = None
            next_item["last_refresh_error"] = None
            next_item["last_refresh_error_at"] = None

            account = self._normalize_account(next_item)
            if account is None:
                return old_token

            rotated = new_token != old_token
            if rotated:
                self._accounts.pop(old_token, None)
                self._token_aliases[old_token] = new_token
                old_inflight = int(self._image_inflight.pop(old_token, 0))
                if old_inflight:
                    self._image_inflight[new_token] = int(self._image_inflight.get(new_token, 0)) + old_inflight
            self._accounts[new_token] = account
            self._save_accounts()
            self._image_slot_condition.notify_all()

        log_service.add(
            LOG_TYPE_ACCOUNT,
            "refresh_token 已刷新 access_token",
            {"source": event, "token": anonymize_token(new_token), "rotated": rotated},
        )
        return new_token

    def _start_relogin_worker(self) -> None:
        """启动后台异步邮箱验证码重新登录自愈工作线程。"""
        t = Thread(target=self._relogin_worker_loop, name="EmailOtpReloginWorker", daemon=True)
        t.start()

    def _relogin_worker_loop(self) -> None:
        """后台异步处理异常账号的重登任务。"""
        while True:
            try:
                item = self._relogin_queue.get()
                if item is None:
                    break
                access_token, email, proxy = item
                self._execute_relogin_with_retry(access_token, email, proxy)
            except Exception as e:
                logger.error(f"[ReloginWorker] Loop error: {e}", exc_info=True)
            finally:
                try:
                    self._relogin_queue.task_done()
                except Exception:
                    pass

    def enqueue_relogin(self, access_token: str, email: str, proxy: Any = None) -> bool:
        """将异常账号加入后台邮箱重登自愈队列（防并发重复入队）。"""
        if not email:
            return False
        with self._relogin_lock:
            if email in self._relogin_in_flight or access_token in self._relogin_in_flight:
                logger.debug(f"[Relogin] 账号 {email} 已在重登队列或正在处理中，跳过重复入队")
                return False
            self._relogin_in_flight.add(email)
            self._relogin_in_flight.add(access_token)
            self._relogin_queue.put((access_token, email, proxy))
            logger.info(f"📥 [Relogin] 异常账号 {email} 已加入后台邮箱验证码重登自愈队列")
            return True

    def _execute_relogin_with_retry(self, access_token: str, email: str, proxy: Any = None) -> None:
        """执行重试逻辑：尝试第 1 次，失败立即重试第 2 次；连续 2 次失败则物理删除。"""
        try:
            logger.info(f"🔄 [Relogin] 开始为异常账号 {email} 执行邮箱验证码自愈 (第 1 次尝试)...")
            res = self.login_with_email_otp(email, proxy)
            if not res.get("ok"):
                logger.warning(f"⚠️ [Relogin] 账号 {email} 第 1 次重登失败: {res.get('error')}，立即执行第 2 次重试...")
                time.sleep(2)
                res = self.login_with_email_otp(email, proxy)

            if res.get("ok"):
                new_token = str(res.get("access_token") or "").strip()
                new_session = str(res.get("session_token") or "").strip()
                token_data = {
                    "access_token": new_token,
                    "session_token": new_session,
                }
                self._apply_refreshed_tokens(access_token, token_data, "email_otp_relogin")
                self.update_account(
                    new_token,
                    {
                        "status": "正常",
                        "invalid_count": 0,
                        "last_invalid_at": None,
                        "quota": 25,
                        "device_id": res.get("device_id"),
                        "oai-device-id": res.get("device_id"),
                        "user-agent": res.get("user_agent"),
                        "token_updated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                    },
                    quiet=True,
                )
                try:
                    self.fetch_remote_info(new_token, "relogin_sync")
                except Exception:
                    pass
                self._notify_pool_health_change()
                log_service.add(
                    LOG_TYPE_ACCOUNT,
                    "邮箱验证码重登自愈成功",
                    {
                        "email": email,
                        "old_token": anonymize_token(access_token),
                        "new_token": anonymize_token(new_token),
                        "status": "正常",
                    },
                )
                logger.info(f"🎉 [Relogin] 账号 {email} 邮箱验证码重登自愈成功！新 Token 已生效，状态恢复为 正常")
            else:
                err_msg = res.get("error")
                logger.warning(f"❌ [Relogin] 账号 {email} 连续 2 次重登失败 ({err_msg})，执行物理删除！")
                self.delete_accounts([access_token])
                self._notify_pool_health_change()
                log_service.add(
                    LOG_TYPE_ACCOUNT,
                    "自动删除重登失败账号",
                    {
                        "email": email,
                        "token": anonymize_token(access_token),
                        "reason": f"relogin_failed_twice: {err_msg}",
                    },
                )
        except Exception as exc:
            logger.error(f"[Relogin] 账号 {email} 重登自愈处理异常: {exc}", exc_info=True)
            self.delete_accounts([access_token])
            self._notify_pool_health_change()
        finally:
            with self._relogin_lock:
                self._relogin_in_flight.discard(email)
                self._relogin_in_flight.discard(access_token)

    def ping_account_heartbeat(self, access_token: str) -> bool:
        """轻量心跳探测，若发现 401 吊销则自动触发邮箱验证码重登自愈。"""
        account = self.get_account(access_token)
        if not account:
            return False
        token = str(account.get("access_token") or access_token)

        try:
            from services.openai_backend_api import InvalidAccessTokenError, OpenAIBackendAPI
            backend = OpenAIBackendAPI(token)
            try:
                me = backend._get_me()
                if me and (me.get("id") or me.get("email")):
                    self.update_account(token, {"status": "正常", "invalid_count": 0}, quiet=True)
                    return True
            finally:
                backend.close()
        except InvalidAccessTokenError:
            self.remove_invalid_token(token, "heartbeat_401")
        except Exception as e:
            logger.debug(f"Heartbeat ping error for {account.get('email')}: {e}")
        return False

    def recover_account_disaster(self, access_token: str) -> bool:
        """容灾自愈入口：将失效账号投递至后台邮箱验证码重登自愈队列。"""
        account = self.get_account(access_token)
        if not account:
            return False
        email = str(account.get("email") or "").strip()
        if email:
            return self.enqueue_relogin(access_token, email, account.get("proxy"))
        return False

    def refresh_access_token(self, access_token: str, *, force: bool = False, event: str = "refresh_access_token") -> str:
        if not access_token:
            return ""
        with self._token_refresh_lock:
            resolved_token, account = self._get_account_for_token(access_token)
            if not account:
                return access_token
            active_token = str(account.get("access_token") or resolved_token or access_token)
            if not self._token_needs_refresh(active_token, force=force):
                return active_token
            refresh_token = str(account.get("refresh_token") or "").strip()
            if not refresh_token:
                # 无 refresh_token 账号，若开启自愈则触发邮箱验证码重登
                email = str(account.get("email") or "").strip()
                if email and getattr(config, "auto_relogin_after_refresh", True):
                    self.enqueue_relogin(active_token, email, account.get("proxy"))
                return active_token
            if not force and self._recent_token_refresh_error(account):
                return active_token
            try:
                token_data = self._request_access_token_refresh(refresh_token, account)
            except Exception as exc:
                error_str = str(exc or "")
                self._record_token_refresh_error(active_token, event, error_str)
                # 如果是 app_session_terminated 错误，尝试邮箱重登自愈
                if "app_session_terminated" in error_str.lower():
                    email = str(account.get("email") or "").strip()
                    if email and getattr(config, "auto_relogin_after_refresh", True):
                        self.enqueue_relogin(active_token, email, account.get("proxy"))
                return active_token
            return self._apply_refreshed_tokens(active_token, token_data, event)

    def login_with_email_otp(self, email_addr: str, proxy: Any = None) -> dict[str, Any]:
        """通过 OpenAI 官方 ChatGPT Web 免密邮箱验证码协议重新登录，换取全新 AccessToken。"""
        from curl_cffi import requests
        from services.register.auth_solver import _load_auth_core, generate_sentinel_payload
        from services.register.mail_provider import create_mail_provider
        from services.register.register_service import register_service

        reg_cfg = register_service.get_config()
        mail_provider = create_mail_provider(reg_cfg, proxy=proxy)

        proxies = {"http": proxy, "https": proxy} if proxy else None
        session = requests.Session(proxies=proxies, impersonate="chrome")
        session.timeout = 30

        core = _load_auth_core()
        did = str(uuid.uuid4())
        ua = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
        masked_email = email_addr[:3] + "***@" + email_addr.split("@")[-1] if "@" in email_addr else email_addr

        try:
            if core and hasattr(core, "init_auth"):
                try:
                    core_did, core_ua = core.init_auth(
                        session=session,
                        email=email_addr,
                        masked_email=masked_email,
                        proxies=proxies,
                        verify=False,
                    )
                    if core_did:
                        did = core_did
                    if core_ua:
                        ua = core_ua
                except Exception as ie:
                    logger.debug(f"[EmailOTP-Relogin] core.init_auth warning: {ie}")

            reg_ctx: dict[str, Any] = {}
            sentinel_payload = generate_sentinel_payload(
                did=did,
                flow="authorize_continue",
                proxy=proxy,
                user_agent=ua,
                ctx=reg_ctx,
            )

            trace_headers = {
                "traceparent": f"00-{uuid.uuid4().hex}-{format(random.getrandbits(64), '016x')}-01",
                "tracestate": "dd=s:1;o:rum",
                "x-datadog-origin": "rum",
                "x-datadog-parent-id": str(random.getrandbits(64)),
                "x-datadog-sampling-priority": "1",
                "x-datadog-trace-id": str(random.getrandbits(64)),
            }
            headers = {
                "user-agent": ua,
                "accept": "application/json",
                "content-type": "application/json",
                "oai-device-id": did,
                "origin": "https://auth.openai.com",
                "referer": "https://auth.openai.com/create-account",
                "openai-sentinel-token": sentinel_payload,
            }
            headers.update(trace_headers)

            signup_resp = session.post(
                "https://auth.openai.com/api/accounts/authorize/continue",
                headers=headers,
                json={"username": {"value": email_addr, "kind": "email"}, "screen_hint": "login_or_signup"},
                timeout=25,
                verify=False,
            )

            if signup_resp.status_code != 200:
                return {
                    "ok": False,
                    "error": f"authorize_continue_failed_{signup_resp.status_code}",
                    "detail": signup_resp.text[:200],
                }

            # 轮询邮箱获取验证码（提取完成后驱动会自动删除邮件并移入废纸篓）
            otp_code = mail_provider.get_code(
                email_addr,
                token=email_addr,
                timeout=120,
                poll_interval=4,
                log_fn=lambda m: logger.info(f"[EmailOTP-Relogin] {m}"),
            )
            if not otp_code:
                return {"ok": False, "error": "otp_timeout"}

            # 校验验证码
            sentinel_otp = generate_sentinel_payload(
                did=did,
                flow="authorize_continue",
                proxy=proxy,
                user_agent=ua,
                ctx=reg_ctx,
            )
            val_headers = {
                "user-agent": ua,
                "accept": "application/json",
                "content-type": "application/json",
                "oai-device-id": did,
                "origin": "https://auth.openai.com",
                "referer": "https://auth.openai.com/email-verification",
                "openai-sentinel-token": sentinel_otp,
            }
            val_headers.update(trace_headers)

            val_resp = session.post(
                "https://auth.openai.com/api/accounts/email-otp/validate",
                headers=val_headers,
                json={"code": otp_code},
                timeout=20,
                verify=False,
            )

            if val_resp.status_code != 200:
                return {
                    "ok": False,
                    "error": f"otp_validate_failed_{val_resp.status_code}",
                    "detail": val_resp.text[:200],
                }

            val_data = val_resp.json() if val_resp.text else {}
            target_continue_url = str(val_data.get("continue_url") or "")

            if target_continue_url:
                try:
                    session.get(target_continue_url, timeout=25, allow_redirects=True, verify=False)
                except Exception as ce:
                    logger.debug(f"[EmailOTP-Relogin] continue_url error: {ce}")

            # 提取 AccessToken
            access_token = ""
            try:
                sess_resp = session.get("https://chatgpt.com/api/auth/session", timeout=20, verify=False)
                if sess_resp.status_code == 200 and sess_resp.text:
                    sess_data = sess_resp.json()
                    access_token = str(sess_data.get("accessToken") or "").strip()
            except Exception as se:
                logger.debug(f"[EmailOTP-Relogin] session endpoint error: {se}")

            if not access_token and core and hasattr(core, "image2api_data"):
                try:
                    res_data = core.image2api_data(session, target_continue_url, proxies)
                    if res_data and isinstance(res_data, str) and len(res_data) > 50:
                        access_token = res_data
                except Exception:
                    pass

            if not access_token:
                return {"ok": False, "error": "extract_access_token_failed"}

            session_token = ""
            for key in ("__Secure-next-auth.session-token", "__Host-next-auth.session-token"):
                v = session.cookies.get(key)
                if v:
                    session_token = v
                    break
            if not session_token:
                chunks: list[tuple[int, str]] = []
                for cookie in session.cookies.jar:
                    if "next-auth.session-token." in cookie.name:
                        try:
                            idx = int(cookie.name.split(".")[-1])
                            chunks.append((idx, cookie.value))
                        except (ValueError, IndexError):
                            pass
                    elif "next-auth.session-token" in cookie.name:
                        session_token = cookie.value
                        break
                if not session_token and chunks:
                    chunks.sort(key=lambda x: x[0])
                    session_token = "".join(v for _, v in chunks)

            return {
                "ok": True,
                "access_token": access_token,
                "session_token": session_token,
                "device_id": did,
                "user_agent": ua,
            }
        except Exception as exc:
            logger.error(f"[EmailOTP-Relogin] Exception: {exc}", exc_info=True)
            return {"ok": False, "error": f"exception: {exc}"}
        finally:
            try:
                session.close()
            except Exception:
                pass

    def _manual_email_relogin_thread(
        self, access_token: str, email: str, proxy: Any, event: str, progress_id: Optional[str] = None
    ) -> None:
        """手动重新登录线程入口（通过邮箱验证码重登）"""
        try:
            res = self.login_with_email_otp(email, proxy)
            if not res.get("ok"):
                time.sleep(2)
                res = self.login_with_email_otp(email, proxy)

            if res.get("ok"):
                new_token = str(res.get("access_token") or "").strip()
                new_session = str(res.get("session_token") or "").strip()
                token_data = {
                    "access_token": new_token,
                    "session_token": new_session,
                }
                self._apply_refreshed_tokens(access_token, token_data, f"{event}:email_relogin")
                self.update_account(
                    new_token,
                    {
                        "status": "正常",
                        "invalid_count": 0,
                        "last_invalid_at": None,
                        "quota": 25,
                        "device_id": res.get("device_id"),
                        "oai-device-id": res.get("device_id"),
                        "user-agent": res.get("user_agent"),
                        "token_updated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                    },
                    quiet=True,
                )
                try:
                    self.fetch_remote_info(new_token, "relogin_sync")
                except Exception:
                    pass
                self._notify_pool_health_change()
                if progress_id:
                    self.update_relogin_progress(progress_id, access_token, "成功")
            else:
                if progress_id:
                    self.update_relogin_progress(progress_id, access_token, "失败", res.get("error"))
        except Exception as exc:
            if progress_id:
                self.update_relogin_progress(progress_id, access_token, "异常", str(exc))

